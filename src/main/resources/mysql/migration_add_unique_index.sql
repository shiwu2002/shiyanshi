-- 使用数据库
USE lab_reservation;

-- ============================================
-- 1. 添加唯一索引防止同一实验室在同一时间段被重复预约
-- ============================================

-- 添加联合唯一索引：lab_id + reserve_date + time_slot
-- 这是防止超卖的最后一道防线（即使分布式锁失效，数据库也能保证数据一致性）
ALTER TABLE `reservation` 
ADD UNIQUE INDEX `uk_lab_date_timeslot` (`lab_id`, `reserve_date`, `time_slot`);

-- ============================================
-- 2. 查看当前索引情况（验证用）
-- ============================================
SHOW INDEX FROM `reservation`;

-- ============================================
-- 3. 如果已存在重复数据导致添加失败，先清理重复数据
-- ============================================
-- 注意：此操作会删除重复的预约记录，只保留 ID 最小的一条
-- 生产环境执行前请先备份数据！

-- 查找重复数据（仅查询，不删除）
SELECT 
    lab_id, 
    reserve_date, 
    time_slot, 
    COUNT(*) as duplicate_count
FROM reservation
GROUP BY lab_id, reserve_date, time_slot
HAVING COUNT(*) > 1;

